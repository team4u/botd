interface TestContextBundle {
  dir: string;
  artifactsDir: string;
  hub: Awaited<ReturnType<typeof startHub>>;
  hubUrl: string;
  auth: AuthManager;
  user: { id: string; username: string };
  cookie: string;
  node: { id: string; rawToken: string };
  bot: { id: string };
  session: { id: string };
}

async function setupTestContext(t: TestContext): Promise<TestContextBundle> {
  const dir = await mkdtemp(path.join(tmpdir(), 'botd-artifact-stream-'));
  const dbPath = path.join(dir, 'hub.sqlite');
  const artifactsDir = path.join(dir, 'artifacts');
  const adminPassword = 'admin-pass-stream';
  const hub = await startHub({
    port: 0,
    host: '127.0.0.1',
    dbPath,
    adminPassword,
    artifactsDir,
  });
  const hubUrl = `http://127.0.0.1:${hub.port}`;
  const auth = new AuthManager();

  t.after(async () => {
    await hub.close();
    await rm(dir, { recursive: true, force: true });
  });

  const userId = 'user_' + randomUUID();
  const username = 'alice';
  const password = 'alice-password-123';
  hub.db.createUser({
    id: userId,
    username,
    passwordHash: auth.hashPassword(password),
    role: 'member',
  });

  const loginRes = await hub.app.request('/api/auth/login', {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ username, password }),
  });
  assert.equal(loginRes.status, 200, 'User login should succeed');
  const cookie = loginRes.headers.get('set-cookie')?.split(';')[0];
  assert.ok(cookie, 'Cookie must be present');

  const nodeId = 'node_' + randomUUID();
  const rawToken = 'node-token-' + randomBytes(16).toString('hex');
  hub.db.createNode({
    id: nodeId,
    name: 'Streaming Node',
    platform: 'linux',
    tokenHash: auth.hashToken(rawToken),
    ownerId: userId,
  });

  const botId = 'bot_' + randomUUID();
  hub.db.saveBot({
    id: botId,
    nodeId,
    name: 'StreamingBot',
    description: 'Bot for artifact streaming tests',
    modelProvider: 'openai',
    modelId: 'gpt-4o',
    enabledSkills: [],
    updatedAt: new Date().toISOString(),
  });

  const sessionId = 'sess_' + randomUUID();
  hub.db.createSession({
    id: sessionId,
    title: 'Streaming Test Session',
    leadBotId: botId,
    ownerId: userId,
  });

  return {
    dir,
    artifactsDir,
    hub,
    hubUrl,
    auth,
    user: { id: userId, username },
    cookie,
    node: { id: nodeId, rawToken },
    bot: { id: botId },
    session: { id: sessionId },
  };
}

function requestOverSocket<T>(
  socketPath: string,
  url: string,
  payload: unknown,
): Promise<{ status: number; json: T }> {
  const data = JSON.stringify(payload);
  return new Promise((resolve, reject) => {
    const req = http.request(
      {
        socketPath,
        path: url,
        method: 'POST',
        headers: {
          'content-type': 'application/json',
          'content-length': Buffer.byteLength(data),
        },
      },
      (res) => {
        let resBody = '';
        res.setEncoding('utf8');
        res.on('data', (c) => { resBody += c; });
        res.on('end', () => {
          let parsed: any;
          try {
            parsed = JSON.parse(resBody);
          } catch {
            parsed = resBody;
          }
          resolve({ status: res.statusCode || 500, json: parsed });
        });
      }
    );
    req.on('error', reject);
    req.write(data);
    req.end();
  });
}

test('Binary stream upload with user Cookie & inline download', { timeout: 60_000 }, async (t) => {
  const ctx = await setupTestContext(t);
  const binaryPayload = randomBytes(64 * 1024); // 64KB
  const filename = '测试 报告 1.dat';
  const messageText = 'Here is the report generated by cookie user.';

  const uploadRes = await ctx.hub.app.request(
    `/api/sessions/${ctx.session.id}/artifacts`,
    {
      method: 'POST',
      headers: {
        cookie: ctx.cookie,
        'content-type': 'application/octet-stream',
        'x-artifact-filename': encodeURIComponent(filename),
        'x-artifact-mime-type': 'application/octet-stream',
        'x-artifact-message': encodeURIComponent(messageText),
      },
      body: binaryPayload,
    }
  );

  assert.equal(uploadRes.status, 201, 'Binary upload should return 201');
  const uploadJson = await uploadRes.json();
  assert.ok(uploadJson.id.startsWith('art_'));
  assert.equal(uploadJson.sessionId, ctx.session.id);
  assert.equal(uploadJson.filename, filename);
  assert.equal(uploadJson.sizeBytes, binaryPayload.length);
  assert.equal(uploadJson.url, `/api/artifacts/${uploadJson.id}/content`);

  // Verify byte-level persistence on disk
  const diskPath = path.join(ctx.artifactsDir, uploadJson.id);
  assert.ok(fs.existsSync(diskPath), 'File should exist on disk');
  const savedBytes = fs.readFileSync(diskPath);
  assert.deepEqual(savedBytes, binaryPayload, 'Saved file bytes must match uploaded bytes exactly');

  // Verify public screen message created
  const messages = ctx.hub.db.getMessages(ctx.session.id);
  const msg = messages.find((m) => m.content === messageText);
  assert.ok(msg, 'Public screen message should be created');
  assert.equal(msg.role, 'assistant');
  assert.equal(msg.attachments?.length, 1);
  assert.equal(msg.attachments[0].id, uploadJson.id);
  assert.equal(msg.attachments[0].filename, filename);
  assert.equal(msg.attachments[0].sizeBytes, binaryPayload.length);

  // Verify streaming download via GET /api/artifacts/:id/content
  const downloadRes = await ctx.hub.app.request(
    `/api/artifacts/${uploadJson.id}/content`,
    {
      method: 'GET',
      headers: { cookie: ctx.cookie },
    }
  );

  assert.equal(downloadRes.status, 200);
  assert.equal(downloadRes.headers.get('content-type'), 'application/octet-stream');
  assert.equal(
    downloadRes.headers.get('content-disposition'),
    `inline; filename="${encodeURIComponent(filename)}"`
  );
  assert.equal(downloadRes.headers.get('x-artifact-id'), uploadJson.id);
  assert.equal(downloadRes.headers.get('x-artifact-session-id'), ctx.session.id);
  assert.equal(downloadRes.headers.get('x-artifact-size-bytes'), String(binaryPayload.length));

  const downloadedBuf = Buffer.from(await downloadRes.arrayBuffer());
  assert.deepEqual(downloadedBuf, binaryPayload, 'Downloaded bytes must match uploaded bytes');
});

test('Binary stream upload with x-botd-node-id & x-botd-node-token authentication', { timeout: 60_000 }, async (t) => {
  const ctx = await setupTestContext(t);
  const binaryPayload = randomBytes(32 * 1024); // 32KB
  const filename = 'node-result.bin';
  const messageText = 'Node upload message with bot attachment';

  const uploadRes = await ctx.hub.app.request(
    `/api/sessions/${ctx.session.id}/artifacts`,
    {
      method: 'POST',
      headers: {
        'x-botd-node-id': ctx.node.id,
        'x-botd-node-token': ctx.node.rawToken,
        'content-type': 'application/octet-stream',
        'x-artifact-filename': encodeURIComponent(filename),
        'x-artifact-bot-id': ctx.bot.id,
        'x-artifact-message': encodeURIComponent(messageText),
      },
      body: binaryPayload,
    }
  );

  assert.equal(uploadRes.status, 201, 'Node upload should return 201');
  const uploadJson = await uploadRes.json();
  assert.equal(uploadJson.senderBotId, ctx.bot.id);
  assert.equal(uploadJson.filename, filename);
  assert.equal(uploadJson.sizeBytes, binaryPayload.length);

  // Verify disk content
  const diskPath = path.join(ctx.artifactsDir, uploadJson.id);
  const savedBytes = fs.readFileSync(diskPath);
  assert.deepEqual(savedBytes, binaryPayload);

  // Verify public message attribution
  const messages = ctx.hub.db.getMessages(ctx.session.id);
  const msg = messages.find((m) => m.content === messageText);
  assert.ok(msg, 'Message should exist');
  assert.equal(msg.senderBotId, ctx.bot.id);
  assert.equal(msg.attachments?.[0].id, uploadJson.id);

  // Verify node can download with node headers
  const downloadRes = await ctx.hub.app.request(
    `/api/artifacts/${uploadJson.id}/content`,
    {
      method: 'GET',
      headers: {
        'x-botd-node-id': ctx.node.id,
        'x-botd-node-token': ctx.node.rawToken,
      },
    }
  );

  assert.equal(downloadRes.status, 200);
  assert.equal(downloadRes.headers.get('x-artifact-sender-bot-id'), ctx.bot.id);
  const downloadedBuf = Buffer.from(await downloadRes.arrayBuffer());
  assert.deepEqual(downloadedBuf, binaryPayload);
});

