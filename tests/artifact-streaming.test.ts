test('Binary upload validations and error handling', { timeout: 60_000 }, async (t) => {
  const ctx = await setupTestContext(t);

  // 1. Empty body (0 bytes)
  const emptyRes = await ctx.hub.app.request(
    `/api/sessions/${ctx.session.id}/artifacts`,
    {
      method: 'POST',
      headers: {
        cookie: ctx.cookie,
        'content-type': 'application/octet-stream',
        'x-artifact-filename': 'empty.bin',
      },
      body: new Uint8Array(0),
    }
  );
  assert.equal(emptyRes.status, 400);
  const emptyJson = await emptyRes.json();
  assert.match(emptyJson.error, /empty/i);

  // 2. Missing filename
  const noFilenameRes = await ctx.hub.app.request(
    `/api/sessions/${ctx.session.id}/artifacts`,
    {
      method: 'POST',
      headers: {
        cookie: ctx.cookie,
        'content-type': 'application/octet-stream',
      },
      body: Buffer.from('content'),
    }
  );
  assert.equal(noFilenameRes.status, 400);
  const noFilenameJson = await noFilenameRes.json();
  assert.match(noFilenameJson.error, /filename/i);

  // 3. Oversized body (>15MB)
  const hugeBuf = Buffer.alloc(MAX_ARTIFACT_BYTES + 1024);
  const hugeRes = await ctx.hub.app.request(
    `/api/sessions/${ctx.session.id}/artifacts`,
    {
      method: 'POST',
      headers: {
        cookie: ctx.cookie,
        'content-type': 'application/octet-stream',
        'x-artifact-filename': 'huge.bin',
      },
      body: hugeBuf,
    }
  );
  assert.equal(hugeRes.status, 413);
  const hugeJson = await hugeRes.json();
  assert.match(hugeJson.error, /too large/i);

  // 4. Invalid node token
  const badNodeRes = await ctx.hub.app.request(
    `/api/sessions/${ctx.session.id}/artifacts`,
    {
      method: 'POST',
      headers: {
        'x-botd-node-id': ctx.node.id,
        'x-botd-node-token': 'wrong-token',
        'content-type': 'application/octet-stream',
        'x-artifact-filename': 'node.bin',
      },
      body: Buffer.from('data'),
    }
  );
  assert.equal(badNodeRes.status, 401);

  // 5. Non-existent session
  const noSessionRes = await ctx.hub.app.request(
    `/api/sessions/non_existent_session/artifacts`,
    {
      method: 'POST',
      headers: {
        cookie: ctx.cookie,
        'content-type': 'application/octet-stream',
        'x-artifact-filename': 'file.bin',
      },
      body: Buffer.from('data'),
    }
  );
  assert.equal(noSessionRes.status, 404);

  // 6. Cross-user session forbidden
  const otherUserId = 'user_other';
  ctx.hub.db.createUser({
    id: otherUserId,
    username: 'bob',
    passwordHash: 'hash',
    role: 'member',
  });
  const otherSessionId = 'sess_other';
  ctx.hub.db.createSession({
    id: otherSessionId,
    title: 'Bob Session',
    leadBotId: ctx.bot.id,
    ownerId: otherUserId,
  });

  const forbiddenRes = await ctx.hub.app.request(
    `/api/sessions/${otherSessionId}/artifacts`,
    {
      method: 'POST',
      headers: {
        cookie: ctx.cookie, // Alice trying to upload to Bob's session
        'content-type': 'application/octet-stream',
        'x-artifact-filename': 'file.bin',
      },
      body: Buffer.from('data'),
    }
  );
  assert.equal(forbiddenRes.status, 403);
});

test('Backwards compatible JSON Base64 upload', { timeout: 60_000 }, async (t) => {
  const ctx = await setupTestContext(t);
  const content = 'Legacy json base64 uploaded text.';
  const contentBase64 = Buffer.from(content).toString('base64');
  const messageText = 'Compat upload message';

  const res = await ctx.hub.app.request(
    `/api/sessions/${ctx.session.id}/artifacts`,
    {
      method: 'POST',
      headers: {
        cookie: ctx.cookie,
        'content-type': 'application/json',
      },
      body: JSON.stringify({
        filename: 'compat.txt',
        mimeType: 'text/plain',
        contentBase64,
        senderBotId: ctx.bot.id,
        message: messageText,
      }),
    }
  );

  assert.equal(res.status, 201);
  const json = await res.json();
  assert.equal(json.filename, 'compat.txt');
  assert.equal(json.sizeBytes, Buffer.byteLength(content));

  const messages = ctx.hub.db.getMessages(ctx.session.id);
  const msg = messages.find((m) => m.content === messageText);
  assert.ok(msg);
  assert.equal(msg.attachments?.[0].id, json.id);

  // Download matches
  const dlRes = await ctx.hub.app.request(`/api/artifacts/${json.id}/content`, {
    headers: { cookie: ctx.cookie },
  });
  assert.equal(dlRes.status, 200);
  const dlText = await dlRes.text();
  assert.equal(dlText, content);
});

test('Node Local IPC binary stream upload (/artifact/put) & download (/artifact/pull)', { timeout: 60_000 }, async (t) => {
  const ctx = await setupTestContext(t);

  const socketPath = getDaemonSocketPath(ctx.dir);

  const ipcDeps: ControlDeps = {
    identity: {
      nodeId: ctx.node.id,
      name: 'node-test',
      hubUrl: ctx.hubUrl,
      token: ctx.node.rawToken,
    },
    dataDir: ctx.dir,
    socketPath,
    startedAt: Date.now(),
    isHubConnected: () => true,
    ipcToken: null,
    syncRegistrationWithHub: async () => {},
    handleShutdown: async () => {},
  };

  const ipcServer = createDaemonControlServer(ipcDeps);
  await new Promise<void>((resolve) => ipcServer.listen(socketPath, resolve));
  t.after(async () => {
    await new Promise<void>((resolve) => ipcServer.close(() => resolve()));
  });

  // 1. Test /artifact/put with filePath
  const originalFilePayload = randomBytes(48 * 1024);
  const localSourceFile = path.join(ctx.dir, 'source-upload.bin');
  await writeFile(localSourceFile, originalFilePayload);

  const putRes = await requestOverSocket<any>(socketPath, '/artifact/put', {
    sessionId: ctx.session.id,
    botId: ctx.bot.id,
    filePath: localSourceFile,
    message: 'IPC put stream message',
  });

  assert.equal(putRes.status, 200);
  assert.ok(putRes.json.ok);
  const uploadedArtId = putRes.json.id || putRes.json.artifact?.id;
  assert.ok(uploadedArtId);
  assert.equal(putRes.json.filename, 'source-upload.bin');

  // Verify Hub actually received the file
  const hubSavedPath = path.join(ctx.artifactsDir, uploadedArtId);
  assert.ok(fs.existsSync(hubSavedPath));
  assert.deepEqual(fs.readFileSync(hubSavedPath), originalFilePayload);

  // 2. Test /artifact/pull with outputPath
  const pulledFileDest = path.join(ctx.dir, 'downloaded-output.bin');
  const pullRes = await requestOverSocket<any>(socketPath, '/artifact/pull', {
    artifactId: uploadedArtId,
    outputPath: pulledFileDest,
  });

  assert.equal(pullRes.status, 200);
  assert.ok(pullRes.json.ok);
  assert.equal(pullRes.json.savedTo, path.resolve(pulledFileDest));

  // Verify content on disk
  assert.ok(fs.existsSync(pulledFileDest));
  const pulledBytes = fs.readFileSync(pulledFileDest);
  assert.deepEqual(pulledBytes, originalFilePayload, 'Pulled file bytes must match original');

  // 3. Test /artifact/pull without outputPath (returns contentBase64)
  const pullBase64Res = await requestOverSocket<any>(socketPath, '/artifact/pull', {
    artifactId: uploadedArtId,
  });
  assert.equal(pullBase64Res.status, 200);
  assert.ok(pullBase64Res.json.ok);
  assert.equal(pullBase64Res.json.contentBase64, originalFilePayload.toString('base64'));
});
